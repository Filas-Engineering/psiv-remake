"""Writes the traceability report: every requirement in docs/spec, the checks covering it, and their status."""

import argparse
import sys
from collections import Counter
from pathlib import Path

import check_spec
import spec as specmod

STATUSES = ("PASS", "FAIL", "NOT IMPLEMENTED", "NOT AUTOMATABLE")
SYSTEM_NAMES = {"FLOW": "Game flow", "FLD": "Field", "ENC": "Encounters", "BAT": "Battle", "TXT": "Dialogue and text", "EVT": "Events and live panels", "UI": "Menus and UI", "SAV": "Save and progression"}


def read_results(path):
	results = {}
	lines = Path(path).read_text(encoding="utf-8").splitlines()[1:]
	for line in lines:
		identifier, status, _, reason = line.split("\t", 3)
		results[identifier] = (status, reason)
	return results


def requirement_status(statuses):
	if not statuses:
		return "no check"
	for worst in ("FAIL", "NOT IMPLEMENTED"):
		if worst in statuses:
			return worst
	if all(s == "PASS" for s in statuses):
		return "PASS"
	if all(s == "NOT AUTOMATABLE" for s in statuses):
		return "NOT AUTOMATABLE"
	return "PASS (automated part)"


def cell(text):
	return text.replace("|", "\\|").replace("\n", " ")


def main():
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--root", default="..")
	parser.add_argument("--results", default="build/results.tsv")
	parser.add_argument("--out", default="report.md")
	args = parser.parse_args()
	spec = specmod.load(Path(args.root))
	results = read_results(args.results)
	errors, warnings = check_spec.check(spec)

	covering, baseline_of = {}, {}
	for c in spec.checks.values():
		for r in c.verifies:
			covering.setdefault(r, []).append(c.id)
		for b in c.baselines:
			baseline_of.setdefault(b, []).append(c.id)

	out = ["# Acceptance traceability report", ""]
	out.append("Generated by `make report` from `docs/spec/*.md` and the last `make test` run (`build/results.tsv`). Do not edit by hand.")
	out.append("")

	check_counts = Counter(results[c][0] for c in spec.checks if c in results)
	out += ["## Checks", "", "| Status | Checks |", "|---|---|"]
	for s in STATUSES:
		out.append(f"| {s} | {check_counts.get(s, 0)} |")
	out.append("")
	out += ["| Check | Runs on | Status | Reason |", "|---|---|---|---|"]
	for c in spec.checks.values():
		status, reason = results.get(c.id, ("not run", ""))
		out.append(f"| {c.id} | {cell(c.runs_on_text)} | {status} | {cell(reason)} |")
	out.append("")

	rows, per_system = [], {}
	for r in spec.requirements.values():
		checks = covering.get(r.id, [])
		statuses = [results[c][0] for c in checks if c in results]
		status = requirement_status(statuses)
		if not checks and r.id in baseline_of:
			status = "baseline only"
		rows.append((r, checks, status))
		per_system.setdefault(r.system, []).append((r, checks, status))

	out += ["## Totals per system", ""]
	columns = ["Requirements", "Covered", "No check", "PASS", "FAIL", "NOT IMPLEMENTED", "NOT AUTOMATABLE", "PASS (automated part)", "To measure"]
	out.append("| System | " + " | ".join(columns) + " |")
	out.append("|---|" + "---|" * len(columns))
	grand = Counter()
	for system, items in per_system.items():
		counts = Counter(status for _, _, status in items)
		values = {
			"Requirements": len(items),
			"Covered": sum(1 for _, checks, _ in items if checks),
			"No check": sum(1 for _, checks, _ in items if not checks),
			"To measure": sum(1 for r, _, _ in items if r.label == "To measure"),
		}
		for s in ("PASS", "FAIL", "NOT IMPLEMENTED", "NOT AUTOMATABLE", "PASS (automated part)"):
			values[s] = counts.get(s, 0)
		grand.update(values)
		out.append(f"| {SYSTEM_NAMES.get(system, system)} ({system}) | " + " | ".join(str(values[c]) for c in columns) + " |")
	out.append("| All | " + " | ".join(str(grand[c]) for c in columns) + " |")
	out.append("")
	out.append("A requirement's status is the worst of its checks' statuses: FAIL, then NOT IMPLEMENTED. \"PASS (automated part)\" means its automated checks pass and the rest run on the engine or in playtests.")
	out.append("")

	out += ["## Requirements", "", "| ID | Label | Checks | Status |", "|---|---|---|---|"]
	for r, checks, status in rows:
		listed = ", ".join(f"{c} ({results[c][0]})" if c in results else c for c in checks)
		if r.id in baseline_of:
			listed += ("; " if listed else "") + "baseline for " + ", ".join(baseline_of[r.id])
		out.append(f"| {r.id} | {r.label} | {listed or '-'} | {status} |")
	out.append("")

	out += ["## Requirements with no check", ""]
	uncovered = [(r, s) for r, checks, s in rows if not checks]
	out.append(f"{len(uncovered)} requirements are verified by no acceptance check. Those marked \"baseline only\" are To measure rows that a check waits on.")
	out.append("")
	for system in per_system:
		items = [(r, s) for r, s in uncovered if r.system == system]
		if items:
			out.append(f"- {SYSTEM_NAMES.get(system, system)}: " + ", ".join(f"{r.id}{' (baseline only)' if s == 'baseline only' else ''}" for r, s in items))
	out.append("")

	out += ["## Spec consistency", ""]
	out.append(f"{len(errors)} error(s), {len(warnings)} warning(s).")
	out.append("")
	out += [f"- error: {cell(e)}" for e in errors]
	out += [f"- warning: {cell(w)}" for w in warnings]
	out.append("")

	Path(args.out).write_text("\n".join(out), encoding="utf-8")
	print(f"wrote {args.out}: {len(rows)} requirements, {len(uncovered)} with no check")
	return 0


if __name__ == "__main__":
	sys.exit(main())
