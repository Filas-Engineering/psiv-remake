#!/usr/bin/env python3
"""Copies the placeholder data for arrival_followers.txt: followers given a cell on the frame the party lands.

* game.json `followers_arrive` "stacked", `followers_on_exits` true, a new game of two (fighter and mystic) in a
  generated interior, `arrival_room` (a town area with Saltgrass's region and no `arrival`, test-only), holding three
  Homing Shells, with Saltgrass and Tidewater among the towns from the start (`start_towns`);
* Saltgrass's `return` lands on the generated field `arrival_field` (12x8, test-only, marker `landing`), with no
  `followers` of its own, so the followers stand stacked on the leader;
* on landing a load hook (`arrival_land`, blocked by the flag `arrival.warped`) runs a scene: a warp with `followers up`,
  a line, a warp with no `followers` word (stacked), a line, a warp with `followers left` against a wall (stacked, the
  cell to the left not walkable), a line;
* the event `arrival_dialogue` (a line only), for a dialogue over followers placed by the developer's warp;
* game.json's `map_load_hold_ms` 300, the interior playing `field_marsh_reeds` and the field `town_canal_market`,
  Saltgrass's track, so a warp between the field and Saltgrass keeps its music through the hold.

Usage: make_arrival_data.py GAME_DATA CORE_DATA OUT

OUT gets game/data and core/data side by side, where game.json's core_data looks.
"""

import json
import shutil
import sys
from pathlib import Path

STRINGS = {
	"en": {
		"area.arrival_room": "Arrival Room",
		"area.arrival_field": "Arrival Field",
	},
	"ja": {
		"area.arrival_room": "到着の部屋",
		"area.arrival_field": "到着の野",
	},
}

LINES = {
	"en": [
		"arrival.up = The line stands north of the leader.",
		"arrival.stacked = The line stands on the leader.",
		"arrival.wall = A wall to the west: the line stands on the leader.",
		"arrival.talk = A word while the line stands still.",
	],
	"ja": [
		"arrival.up = 列はリーダーの北に立つ。",
		"arrival.stacked = 列はリーダーの上に立つ。",
		"arrival.wall = 西は壁。列はリーダーの上に立つ。",
		"arrival.talk = 列が止まっている間の一言。",
	],
}

ROOM = {
	"id": "arrival_room", "kind": "town", "encounter_mode": "random", "step_ms": 250, "region": "coast", "music": "field_marsh_reeds",
	"name": "area.arrival_room",
	"map": ["########", "#......#", "#......#", "#......#", "########"],
	"markers": {"middle": [3, 2]},
}
FIELD = {
	"id": "arrival_field", "kind": "town", "encounter_mode": "random", "step_ms": 250, "music": "town_canal_market",
	"name": "area.arrival_field",
	"map": ["############"] + ["#..........#"] * 6 + ["############"],
	"markers": {"landing": [3, 4], "north_spot": [6, 4], "south_spot": [9, 5], "wall_spot": [1, 2]},
	"hooks": [{"id": "land", "trigger": "load", "event": "arrival_land", "block_flag": "arrival.warped"}],
}
EVENTS = """# Generated by make_arrival_data.py: warps that place the followers while a scene runs.

event arrival_land unskippable
	lock player
	set arrival.warped
	warp arrival_field north_spot followers up
	say guide @arrival.up
	warp arrival_field south_spot
	say guide @arrival.stacked
	warp arrival_field wall_spot followers left
	say guide @arrival.wall
	unlock player
end

event arrival_dialogue unskippable
	say guide @arrival.talk
end
"""


def load(path):
	return json.loads(path.read_text())


def save(path, data):
	path.write_text(json.dumps(data, indent="\t", ensure_ascii=False) + "\n")


def main():
	game, core, out = (Path(a) for a in sys.argv[1:4])
	if out.exists():
		shutil.rmtree(out)
	shutil.copytree(game, out / "game" / "data")
	shutil.copytree(core, out / "core" / "data")
	data = out / "game" / "data"

	game_json = load(data / "game.json")
	game_json["followers_arrive"] = "stacked"
	game_json["followers_on_exits"] = True
	game_json["presentation"]["map_load_hold_ms"] = 300
	game_json["start"]["area"] = "arrival_room"
	game_json["start"]["marker"] = "middle"
	game_json["start"]["lineup"] = ["fighter", "mystic"]
	game_json["start"]["items"] = {"tonic": 1, "homing_shell": 3}
	game_json["start_towns"] = ["saltgrass", "tidewater"]
	game_json["flags"] = sorted(game_json["flags"] + ["arrival.warped"])
	for area in (ROOM, FIELD):
		save(data / "areas" / f"{area['id']}.json", area)
		game_json["areas"].append(f"areas/{area['id']}.json")
	(data / "events" / "arrival.ev").write_text(EVENTS)
	game_json["events"].append("events/arrival.ev")
	save(data / "game.json", game_json)

	saltgrass_file = data / "areas" / "saltgrass.json"
	saltgrass = load(saltgrass_file)
	saltgrass["return"] = {"area": "arrival_field", "marker": "landing"}
	save(saltgrass_file, saltgrass)

	for language in game_json["languages"]:
		table_file = data / language["text"]
		table = load(table_file)
		table["text"].update(STRINGS[language["code"]])
		save(table_file, table)
		strings_file = data / language["strings"]
		strings_file.write_text(strings_file.read_text().rstrip("\n") + "\n\n" + "\n".join(LINES[language["code"]]) + "\n")


if __name__ == "__main__":
	main()
