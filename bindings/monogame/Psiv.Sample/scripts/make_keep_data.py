#!/usr/bin/env python3
"""Copies the placeholder data for keep_flows.txt (the save flow, travel messages and a choice that stays on screen):

* a new game of two at level 10 (the fighter, and the mystic, who knows Homeward) at Saltgrass's south gate, holding two
  Homing Shells, Saltgrass the only town visited, so a return finds nowhere to go until Tidewater is visited;
* the event `keep_talk` (events/keep.ev): a choice with `keep` whose options carry states (`new` until each topic was
  heard, `plain` on the last), a line with the guide's portrait over the kept choice, a nested yes/no, `choice clear`,
  a last line; the flags `keep.bell_heard` and `keep.ferry_heard`;
* the event `keep_cli` for the terminal runs (keep_cli.txt), started by Saltgrass's flag hook on `keep.cli`: a kept
  choice answered, a line, the same choice kept again with another answer, a line, so the kept choice changes;
* the event `keep_pages` (choice_flows.txt): a kept choice whose prompt is three pages, with `option back`, then a
  choice without one;
* the event `keep_back`, started by Saltgrass's flag hook on `keep.back`: a kept choice with `option back`, whose back
  branch says the guide's last line.

Usage: make_keep_data.py GAME_DATA CORE_DATA OUT

OUT gets game/data and core/data side by side, where game.json's core_data looks.
"""

import json
import shutil
import sys
from pathlib import Path

LINES = {
	"en": [
		"keep.prompt = What shall we talk about?",
		"keep.header = Topics",
		"keep.bell = The bell",
		"keep.ferry = The ferry",
		"keep.leave = Nothing more",
		"keep.bell_line = It rings at night, east past the reeds.",
		"keep.more = Shall I go on?",
		"keep.more_line = The cove keeps its own hours.",
		"keep.ferry_line = The ferry runs when the tide allows.",
		"keep.done = Come back if you think of more.",
		"keep.pages = The bell rings at night.{page}The ferry runs by the tide.{page}Which shall I tell you about?",
	],
	"ja": [
		"keep.prompt = 調べてくれるかい？",
		"keep.header = 鐘",
		"keep.bell = 鐘",
		"keep.ferry = 港",
		"keep.leave = また来てくれ",
		"keep.bell_line = 鐘のことで来たのかい？毎晩、葦の向こう東の鐘の入り江で鳴るんだ。",
		"keep.more = 調べてくれるかい？",
		"keep.more_line = 気が変わったらまた来てくれ。",
		"keep.ferry_line = 気が変わったらまた来てくれ。",
		"keep.done = 気が変わったらまた来てくれ。",
		"keep.pages = 鐘は夜に鳴る。{page}港は潮で動く。{page}どちらを調べてくれるかい？",
	],
}

EVENTS = """# Generated by make_keep_data.py: a choice that stays on screen while the talk goes on over it.

event keep_talk unskippable
	lock player
	choice @keep.prompt header @keep.header keep
	option @keep.bell state new if not keep.bell_heard
		set keep.bell_heard
		say guide @keep.bell_line as guide_smile
		ask @keep.more
		yes
			say guide @keep.more_line
		no
		end
	option @keep.ferry state new if not keep.ferry_heard
		set keep.ferry_heard
		say guide @keep.ferry_line
	option @keep.leave state plain
	end
	choice clear
	say guide @keep.done
	unlock player
end

event keep_cli unskippable
	set keep.cli_done
	choice @keep.prompt keep
	option @keep.bell state new if not keep.bell_heard
		set keep.bell_heard
	option @keep.ferry
	end
	say guide @keep.bell_line
	choice @keep.prompt keep
	option @keep.bell state new if not keep.bell_heard
	option @keep.ferry
	end
	say guide @keep.done
end

event keep_pages unskippable
	choice @keep.pages keep
	option @keep.bell
		say guide @keep.bell_line
	option @keep.ferry
		say guide @keep.ferry_line
	option back
		say guide @keep.done
	end
	choice @keep.more
	option @keep.bell
	option @keep.ferry
	end
	choice clear
end

event keep_back unskippable
	set keep.back_done
	choice @keep.prompt keep
	option @keep.bell
		say guide @keep.bell_line
	option @keep.ferry
		say guide @keep.ferry_line
	option back
		say guide @keep.done
	end
end
"""


def load(path):
	return json.loads(path.read_text())


def save(path, data):
	path.write_text(json.dumps(data, indent="\t", ensure_ascii=False) + "\n")


def main():
	game, core, out = (Path(a) for a in sys.argv[1:4])
	if out.exists():
		shutil.rmtree(out)
	shutil.copytree(game, out / "game" / "data")
	shutil.copytree(core, out / "core" / "data")
	data = out / "game" / "data"

	game_json = load(data / "game.json")
	game_json["start"].update({"area": "saltgrass", "marker": "south_gate", "facing": "north", "lineup": ["fighter", "mystic"], "level": 10,
		"items": {"tonic": 1, "homing_shell": 2}})
	game_json["flags"] = sorted(game_json["flags"] + ["keep.back", "keep.back_done", "keep.bell_heard", "keep.cli", "keep.cli_done", "keep.ferry_heard"])
	(data / "events" / "keep.ev").write_text(EVENTS)
	game_json["events"].append("events/keep.ev")
	save(data / "game.json", game_json)
	saltgrass_file = data / "areas" / "saltgrass.json"
	saltgrass = load(saltgrass_file)
	saltgrass["hooks"].append({"id": "keep_cli", "trigger": "flag", "event": "keep_cli", "require_flag": "keep.cli", "block_flag": "keep.cli_done"})
	saltgrass["hooks"].append({"id": "keep_back", "trigger": "flag", "event": "keep_back", "require_flag": "keep.back", "block_flag": "keep.back_done"})
	save(saltgrass_file, saltgrass)
	for language in game_json["languages"]:
		strings_file = data / language["strings"]
		strings_file.write_text(strings_file.read_text().rstrip("\n") + "\n\n" + "\n".join(LINES[language["code"]]) + "\n")


if __name__ == "__main__":
	main()
